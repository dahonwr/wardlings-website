/**
 * Formats the real verified allocations list into a clean string (e.g. "OG", "OG + GTD", "OG + GTD + FCFS").
 */
export function formatAllocationsForShare(allocations?: string[]): string {
  if (!allocations || allocations.length === 0) {
    return 'GTD';
  }
  return allocations.join(' + ');
}

/**
 * Randomly picks ONE of the 50 share templates and populates it with verified allocation(s).
 */
export function generateRandomShareText(allocations?: string[]): string {
  const allocationStr = formatAllocationsForShare(allocations);
  const randomIndex = Math.floor(Math.random() * SHARE_TEMPLATES.length);
  const template = SHARE_TEMPLATES[randomIndex] || SHARE_TEMPLATES[0];
  return template.replace(/\{ALLOCATIONS\}/g, allocationStr);
}

/**
 * Generates an X (Twitter) intent share URL from a randomly chosen template among the 50.
 */
export function generateRandomShareOnXUrl(allocations?: string[]): string {
  const text = generateRandomShareText(allocations);
  return `https://x.com/intent/tweet?text=${encodeURIComponent(text)}`;
}
